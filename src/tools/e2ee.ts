export async function changePassphraseForProfile(
  rt: Runtime,
  newPassphrase: string,
): Promise<{ ok: true } | { ok: false; error: string }> {
  if (newPassphrase.length < 16) {
    return { ok: false, error: 'new passphrase must be at least 16 characters' };
  }

  let profile: Record<string, unknown>;
  try {
    profile = JSON.parse(await fs.promises.readFile(rt.paths.e2eeFile, 'utf8')) as Record<string, unknown>;
  } catch {
    return { ok: false, error: 'e2ee.json not found — run e2ee_generate_local first' };
  }

  const enc = typeof profile.enc_priv_key_base64 === 'string' ? profile.enc_priv_key_base64 : '';
  const salt = typeof profile.pbkdf2_salt === 'string' ? profile.pbkdf2_salt : '';
  const iterations =
    typeof profile.pbkdf2_iterations === 'number' ? profile.pbkdf2_iterations : 600_000;
  const pub = typeof profile.pub_key_base64 === 'string' ? profile.pub_key_base64 : '';

  if (!enc || !salt || !pub) {
    return { ok: false, error: 'e2ee.json missing enc_priv_key_base64, pbkdf2_salt, or pub_key_base64' };
  }

  await migrateLegacyPassphraseInJson(rt.paths);

  let oldPassphrase = await readPassphraseFile(rt.paths.e2eePassphraseFile);
  if (!oldPassphrase && rt.cfg.e2eePassphrase) {
    oldPassphrase = rt.cfg.e2eePassphrase;
  }
  if (!oldPassphrase && typeof profile.passphrase === 'string') {
    oldPassphrase = profile.passphrase;
  }
  if (!oldPassphrase) {
    return { ok: false, error: 'no current passphrase — use e2ee-passphrase reveal or check e2ee.passphrase file' };
  }

  let privateKey: Uint8Array;
  try {
    privateKey = unlockPrivateKey(enc, salt, iterations, oldPassphrase);
  } catch {
    return { ok: false, error: 'failed to decrypt private key — wrong passphrase?' };
  }

  if (!verifyPrivateKeyMatchesPub(privateKey, pub)) {
    privateKey.fill(0);
    return { ok: false, error: 'decrypted key does not match pub_key_base64' };
  }

  let reenc: Awaited<ReturnType<typeof reencryptPrivateKey>>;
  try {
    reenc = await reencryptPrivateKey(privateKey, newPassphrase);
  } catch (err) {
    privateKey.fill(0);
    return { ok: false, error: err instanceof Error ? err.message : String(err) };
  } finally {
    privateKey.fill(0);
  }

  profile.enc_priv_key_base64 = reenc.enc_priv_key_base64;
  profile.pbkdf2_salt = reenc.pbkdf2_salt;
  profile.pbkdf2_iterations = reenc.pbkdf2_iterations;
  delete profile.passphrase;

  try {
    await writeJsonAtomic(rt.paths.e2eeFile, profile);
    await writePassphrase(rt.paths, newPassphrase, true);
  } catch (err) {
    return { ok: false, error: err instanceof Error ? err.message : String(err) };
  }

  return { ok: true };
}

export async function revealPassphraseForProfile(rt: Runtime): Promise<string | null> {
  await migrateLegacyPassphraseInJson(rt.paths);
  const fromFile = await readPassphraseFile(rt.paths.e2eePassphraseFile);
  if (fromFile) return fromFile;
  if (rt.cfg.e2eePassphrase) return rt.cfg.e2eePassphrase;
  try {
    const profile = JSON.parse(await fs.promises.readFile(rt.paths.e2eeFile, 'utf8')) as Record<string, unknown>;
    if (typeof profile.passphrase === 'string' && profile.passphrase.trim()) {
      return profile.passphrase.trim();
    }
  } catch {
    // no e2ee.json
  }
  return null;
}
